#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn square_icons_share_one_grid() {
        for icon in [&PHOTO, &BOOK, &BIBLE, &STATS, &GAMES, &AI, &TOOLS] {
            assert_eq!(icon.height(), ICON_SIZE);
            assert!(icon.rows.iter().all(|row| row.len() as i32 == ICON_SIZE));
        }
        assert!(WIFI.rows.iter().all(|row| row.len() as i32 == WIFI.width()));
    }

    #[test]
    fn maps_wmo_codes_to_weather_icons() {
        assert!(core::ptr::eq(weather_icon(0), &SUN));
        assert!(core::ptr::eq(weather_icon(2), &PARTLY_CLOUDY));
        assert!(core::ptr::eq(weather_icon(81), &RAIN));
    }
}
