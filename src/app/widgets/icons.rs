//! Monochrome UI icons rasterized from the SVG symbols in `mockups/index.html`.
//!
//! Each row is pixel art: `#` is ink and `.` is paper, so an icon can be
//! tweaked by editing the strings directly.

use embedded_graphics::{
    pixelcolor::BinaryColor,
    prelude::{DrawTarget, Pixel, Point},
};

/// Edge length of the square menu and weather icons.
pub const ICON_SIZE: i32 = 26;

pub struct Icon {
    pub rows: &'static [&'static str],
}

impl Icon {
    #[must_use]
    pub fn width(&self) -> i32 {
        self.rows.first().map_or(0, |row| row.len() as i32)
    }

    #[must_use]
    pub fn height(&self) -> i32 {
        self.rows.len() as i32
    }

    /// Draw the ink pixels in `color`; paper pixels stay transparent.
    pub fn draw<D>(
        &self,
        display: &mut D,
        top_left: Point,
        color: BinaryColor,
    ) -> Result<(), D::Error>
    where
        D: DrawTarget<Color = BinaryColor>,
    {
        for (y, row) in self.rows.iter().enumerate() {
            for (x, cell) in row.bytes().enumerate() {
                if cell == b'#' {
                    let point = top_left + Point::new(x as i32, y as i32);
                    display.draw_iter(core::iter::once(Pixel(point, color)))?;
                }
            }
        }
        Ok(())
    }

    /// Replicate each ink pixel into a square; zero scale draws nothing.
    pub fn draw_scaled<D>(
        &self,
        display: &mut D,
        top_left: Point,
        scale: u32,
        color: BinaryColor,
    ) -> Result<(), D::Error>
    where
        D: DrawTarget<Color = BinaryColor>,
    {
        if scale == 0 {
            return Ok(());
        }
        for (y, row) in self.rows.iter().enumerate() {
            for (x, cell) in row.bytes().enumerate() {
                if cell == b'#' {
                    for dy in 0..scale {
                        for dx in 0..scale {
                            let point = top_left
                                + Point::new(
                                    (x as u32 * scale + dx) as i32,
                                    (y as u32 * scale + dy) as i32,
                                );
                            display.draw_iter(core::iter::once(Pixel(point, color)))?;
                        }
                    }
                }
            }
        }
        Ok(())
    }
}

/// Pick the icon for one WMO weather interpretation code.
#[must_use]
pub fn weather_icon(code: u16) -> &'static Icon {
    match code {
        0 => &SUN,
        1 | 2 => &PARTLY_CLOUDY,
        45 | 48 => &FOG,
        51..=57 => &DRIZZLE,
        61..=67 | 80..=82 => &RAIN,
        71..=77 | 85 | 86 => &SNOW,
        95..=99 => &THUNDER,
        _ => &CLOUD,
    }
}

/// Like `weather_icon`, with the moon for clear and partly cloudy nights.
#[must_use]
pub fn weather_icon_at(code: u16, is_day: bool) -> &'static Icon {
    match code {
        0 if !is_day => &MOON,
        1 | 2 if !is_day => &PARTLY_CLOUDY_NIGHT,
        _ => weather_icon(code),
    }
}

